package mx.edu.tecdesoftware.recetario.web.controller;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.ExampleObject;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import mx.edu.tecdesoftware.recetario.domain.Recipe;
import mx.edu.tecdesoftware.recetario.domain.service.RecipeService;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;

@RestController
@RequestMapping("/recipes")
@CrossOrigin(origins = "*") // Flutter web corre en otro origen (otro puerto); solo para desarrollo
@Tag(name = "Recipe", description = "Recetas del recetario con su categoría")
public class RecipeController {

    // Ejemplo que muestra Swagger UI en POST y PUT
    private static final String RECIPE_EXAMPLE = """
            {
              "name": "Molletes",
              "description": "Bolillo con frijoles y queso gratinado.",
              "ingredients": "2 bolillos\\n1 taza de frijoles refritos\\n100 g de queso Chihuahua\\nPico de gallo",
              "instructions": "1. Parte los bolillos a la mitad.\\n2. Úntalos con frijoles y agrega el queso.\\n3. Hornea 10 minutos a 180 °C.\\n4. Sirve con pico de gallo.",
              "prepTime": 15,
              "servings": 2,
              "imageUrl": "https://example.com/molletes.jpg",
              "categoryId": 1
            }
            """;

    private final RecipeService recipeService;

    public RecipeController(RecipeService recipeService) {
        this.recipeService = recipeService;
    }

    @Operation(summary = "Get all recipes", description = "Return every recipe ordered by name, with its category")
    @ApiResponse(responseCode = "200", description = "Recipes found")
    @GetMapping("")
    public ResponseEntity<List<Recipe>> getAll() {
        return ResponseEntity.ok(recipeService.getAll());
    }

    @Operation(summary = "Get recipe by ID")
    @ApiResponse(responseCode = "200", description = "Recipe found")
    @ApiResponse(responseCode = "404", description = "Recipe not found")
    @GetMapping("/{id}")
    public ResponseEntity<Recipe> getRecipe(
            @Parameter(description = "ID of the recipe", example = "1", required = true)
            @PathVariable("id") int recipeId) {
        return recipeService.getRecipe(recipeId)
                .map(ResponseEntity::ok)
                .orElse(ResponseEntity.notFound().build());
    }

    @Operation(summary = "Get recipes by category", description = "Return the recipes of a category ordered by name")
    @ApiResponse(responseCode = "200", description = "Recipes of the category (may be empty)")
    @GetMapping("/category/{id}")
    public ResponseEntity<List<Recipe>> getByCategory(
            @Parameter(description = "ID of the category", example = "1", required = true)
            @PathVariable("id") int categoryId) {
        return ResponseEntity.ok(recipeService.getByCategory(categoryId));
    }

    @Operation(summary = "Create a recipe",
            description = "The ID is generated by the database and new recipes are active; recipeId, active and category are ignored")
    @ApiResponse(responseCode = "201", description = "Recipe created, with its category")
    @ApiResponse(responseCode = "400", description = "Invalid data or unknown category")
    @PostMapping("")
    public ResponseEntity<Recipe> save(
            // Nombre completo porque Spring también tiene una anotación @RequestBody
            @io.swagger.v3.oas.annotations.parameters.RequestBody(content = @Content(
                    schema = @Schema(implementation = Recipe.class),
                    examples = @ExampleObject(value = RECIPE_EXAMPLE)))
            @Valid @RequestBody Recipe recipe) {
        return new ResponseEntity<>(recipeService.save(recipe), HttpStatus.CREATED);
    }

    @Operation(summary = "Update a recipe", description = "Replace the data of an existing recipe")
    @ApiResponse(responseCode = "200", description = "Recipe updated, with its category")
    @ApiResponse(responseCode = "400", description = "Invalid data or unknown category")
    @ApiResponse(responseCode = "404", description = "Recipe not found")
    @PutMapping("/{id}")
    public ResponseEntity<Recipe> update(
            @Parameter(description = "ID of the recipe", example = "1", required = true)
            @PathVariable("id") int recipeId,
            @io.swagger.v3.oas.annotations.parameters.RequestBody(content = @Content(
                    schema = @Schema(implementation = Recipe.class),
                    examples = @ExampleObject(value = RECIPE_EXAMPLE)))
            @Valid @RequestBody Recipe recipe) {
        return recipeService.update(recipeId, recipe)
                .map(ResponseEntity::ok)
                .orElse(ResponseEntity.notFound().build());
    }

    @Operation(summary = "Delete a recipe")
    @ApiResponse(responseCode = "200", description = "Recipe deleted")
    @ApiResponse(responseCode = "404", description = "Recipe not found")
    @DeleteMapping("/{id}")
    public ResponseEntity<Void> delete(
            @Parameter(description = "ID of the recipe", example = "1", required = true)
            @PathVariable("id") int recipeId) {
        if (recipeService.delete(recipeId)) {
            return ResponseEntity.ok().build();
        }
        return ResponseEntity.notFound().build();
    }
}
