-- V1: tablas del recetario (la persistencia va en español, como en Market)

CREATE TABLE categorias (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion  VARCHAR(60) NOT NULL UNIQUE,
    estado       BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE recetas (
    id_receta          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(120) NOT NULL,
    descripcion        VARCHAR(300),
    ingredientes       TEXT         NOT NULL,
    instrucciones      TEXT         NOT NULL,
    tiempo_preparacion INTEGER      NOT NULL CHECK (tiempo_preparacion > 0), -- minutos
    porciones          INTEGER      NOT NULL CHECK (porciones > 0),
    id_categoria       INTEGER      NOT NULL REFERENCES categorias (id_categoria),
    estado             BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Supabase expone el esquema "public" en su API REST. Activar RLS sin políticas
-- bloquea ese acceso: solo el backend (dueño de las tablas) puede leer y escribir.
ALTER TABLE categorias ENABLE ROW LEVEL SECURITY;
ALTER TABLE recetas ENABLE ROW LEVEL SECURITY;
ALTER TABLE flyway_schema_history ENABLE ROW LEVEL SECURITY;
